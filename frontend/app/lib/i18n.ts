export type StringKey = keyof (typeof strings)['en'];

// Memoised per locale so callers can list `t` in a dependency array without
// re-running the effect on every render.
export function useTranslation() {
  const {preferences} = usePreferences();
  const {locale} = preferences;
  return useCallback((key: StringKey, values?: Record<string, string | number>): string => {
    const table = strings[locale] ?? strings.en;
    const template: string = table[key] ?? strings.en[key] ?? key;
    if (!values) return template;
    return Object.entries(values).reduce(
      (text, [name, value]) => text.replace(`{${name}}`, String(value)),
      template,
    );
  }, [locale]);
}
